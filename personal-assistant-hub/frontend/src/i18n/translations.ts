const dictionaries: Record<Language, Record<TranslationKey, string>> = { ru, en };

export function translate(
  language: Language,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  let text = dictionaries[language][key] ?? dictionaries.ru[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{\\{${k}\\}\\}`, 'g'), String(v));
    });
  }
  return text;
}

export function startScreenLabel(language: Language, screen: StartScreen): string {
  return translate(language, `startScreen.${screen}` as TranslationKey);
}
